# =====================================================================
# 6. 의미 정규화
#
# 같은 의미를 가진 여러 표현을 하나의 핵심 개념으로 통합
#
# 예:
# 변화했다 / 변화되는 / 변형 → 변화
# 주체적 / 주체적인 → 주체성
# =====================================================================

words_semantic <- words_clean %>%
  mutate(
    
    word = case_when(
      
      # ---------------------------------------------------------------
      # 변화
      # ---------------------------------------------------------------
      
      str_detect(word, "변화|변형") ~ "변화",
      
      
      # ---------------------------------------------------------------
      # 주체성
      # ---------------------------------------------------------------
      
      str_detect(word, "주체") ~ "주체성",
      
      
      # ---------------------------------------------------------------
      # 교육
      # ---------------------------------------------------------------
      
