names(df)

# 예상 결과:
# "1조" "2조" "3조" "4조"


# =====================================================================
# 2. Wide format → Long format
#
# 기존:
# 1조 | 2조 | 3조 | 4조
#
# 변환:
# group | text
# =====================================================================

responses <- df %>%
  pivot_longer(
    cols = everything(),
    names_to = "group",
    values_to = "text"
  ) %>%
  filter(
    !is.na(text),
    text != ""
  )

print(responses)


# =====================================================================
# 3. 텍스트 기본 정제
# =====================================================================

responses <- responses %>%
  mutate(
    text = as.character(text),
    
    # 특수문자 제거
    text = str_replace_all(
      text,
      "[[:punct:]]",
      " "
    ),
    
    # 숫자 제거
    text = str_replace_all(
      text,
      "[0-9]",
      " "
    ),
    
    # 중복 공백 제거
    text = str_squish(text)
  )


# =====================================================================
# 4. 단어 단위 분리
# =====================================================================

words <- responses %>%
  unnest_tokens(
    word,
    text,
    token = "words"
  ) %>%
  
  # 한 글자 단어 제거
  filter(str_length(word) >= 2)


