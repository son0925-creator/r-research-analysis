      # ---------------------------------------------------------------
      # 상호작용 / 만남 / 교류
      # ---------------------------------------------------------------
      
      str_detect(word, "상호|교류|만남|마주") ~ "상호작용",
      
      
      # ---------------------------------------------------------------
      # 리더십
      # ---------------------------------------------------------------
      
