# =====================================================================

word_count <- words_semantic %>%
  count(
    group,
    word,
    sort = TRUE
  )


# =====================================================================
# 9. 조별 의미 가중치
#
# 주의:
# 아래 가중치는 실제 빈도가 아니라
# 연구 질문과 조별 의미구조를 시각적으로 강조하기 위한 값입니다.
# =====================================================================

word_count <- word_count %>%
  mutate(
    
    semantic_weight = case_when(
      
      
      # ===============================================================
      # 1조
      # 상호작용 → 교육 → 주체성 → 변화
      # ===============================================================
      
      group == "1조" &
        word == "상호작용" ~ 2.0,
      
      group == "1조" &
        word == "주체성" ~ 2.0,
      
      group == "1조" &
        word == "변화" ~ 1.8,
      
      group == "1조" &
        word == "교육" ~ 1.7,
      
      group == "1조" &
        word == "역할확대" ~ 1.5,
      
      group == "1조" &
        word == "리더십" ~ 1.5,
      
      
      # ===============================================================
      # 2조
      # 역사·사회적 현실 → 환경 → 리더십 → 변화
      # ===============================================================
      
      group == "2조" &
        word == "환경" ~ 1.8,
      
      group == "2조" &
        word == "현실" ~ 1.8,
      
      group == "2조" &
        word == "역사적맥락" ~ 1.8,
      
      group == "2조" &
        word == "사회적영역" ~ 1.7,
      
      group == "2조" &
        word == "정치적환경" ~ 1.7,
      
      group == "2조" &
        word == "변화" ~ 2.0,
      
      group == "2조" &
        word == "리더십" ~ 1.8,
      
      
      # ===============================================================
      # 3조
      # 가정·사적 영역 → 사회·공적 영역 → 역할 확대
      # ===============================================================
      
      group == "3조" &
        word == "가정적영역" ~ 1.7,
      
      group == "3조" &
        word == "사적영역" ~ 1.8,
      
      group == "3조" &
        word == "사회적영역" ~ 1.8,
      
      group == "3조" &
        word == "공적영역" ~ 2.0,
      
      group == "3조" &
        word == "역할확대" ~ 1.8,
      
      group == "3조" &
        word == "독립성" ~ 2.0,
      
      group == "3조" &
        word == "주체성" ~ 1.8,
      
      group == "3조" &
        word == "리더십" ~ 1.8,
      
      
      # ===============================================================
      # 4조
      # 관계·교육 → 책임·열정 → 주체적 변화
      # ===============================================================
      
      group == "4조" &
        word == "관계형성" ~ 1.8,
      
      group == "4조" &
        word == "상호작용" ~ 2.0,
      
      group == "4조" &
        word == "교육" ~ 1.7,
      
      group == "4조" &
        word == "책임감" ~ 1.8,
      
      group == "4조" &
        word == "열정" ~ 1.7,
      
      group == "4조" &
        word == "변화" ~ 2.0,
      
      group == "4조" &
        word == "주체성" ~ 1.8,
      
      group == "4조" &
        word == "리더십" ~ 1.8,
      
      
      # 그 외의 단어
      TRUE ~ 1
    ),
    
    weighted_n = n * semantic_weight
  )


# =====================================================================
# 10. 각 조별 핵심 단어 선택
# =====================================================================

group1_final <- word_count %>%
  filter(group == "1조") %>%
  arrange(desc(weighted_n)) %>%
  slice_head(n = 24)


group2_final <- word_count %>%
  filter(group == "2조") %>%
  arrange(desc(weighted_n)) %>%
  slice_head(n = 24)


group3_final <- word_count %>%
  filter(group == "3조") %>%
  arrange(desc(weighted_n)) %>%
  slice_head(n = 24)


group4_final <- word_count %>%
  filter(group == "4조") %>%
  arrange(desc(weighted_n)) %>%
  slice_head(n = 22)


# =====================================================================
# 11. 긴 단어에 대한 시각적 크기 보정
#
# 분석값 weighted_n은 그대로 두고
# 그림에서만 사용하는 display_weight를 만듭니다.
# =====================================================================

group1_final <- group1_final %>%
  mutate(display_weight = weighted_n)


group2_final <- group2_final %>%
  mutate(display_weight = weighted_n)


group3_final <- group3_final %>%
  mutate(
    
    display_weight = case_when(
      
      word == "가정적영역" ~ weighted_n * 0.78,
      word == "사회적영역" ~ weighted_n * 0.78,
      word == "공적영역" ~ weighted_n * 0.82,
      word == "사적영역" ~ weighted_n * 0.82,
      word == "역할확대" ~ weighted_n * 0.82,
      
      TRUE ~ weighted_n
    )
  )


group4_final <- group4_final %>%
  mutate(
    
    display_weight = case_when(
      
      word == "상호작용" ~ weighted_n * 0.90,
      word == "관계형성" ~ weighted_n * 0.90,
      word == "선교활동" ~ weighted_n * 0.90,
      word == "역할확대" ~ weighted_n * 0.90,
      
      TRUE ~ weighted_n
    )
  )


